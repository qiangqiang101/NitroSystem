#!/usr/bin/env python3
"""Turns icons/<slot>.png (200x200, small icon) and icons/<slot>_LG.png (916x458, large icon) into src/icon_data.h,
so the DLL can carry the icons and hand them to the game (the mod platform's set_file) without any file on disk.

  python3 scripts/gen_icons.py --prefix nitro [--icons icons] [--out src/icon_data.h]

The block data is run-length packed (16-byte block repeated n times), which is ~4x smaller for flat icons.
"""
import argparse, os, sys, glob
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'icontools'))
from PIL import Image
import swatch

ap = argparse.ArgumentParser()
ap.add_argument('--prefix', required=True)
ap.add_argument('--icons', default=None)
ap.add_argument('--out', default=None)
a = ap.parse_args()
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
icons = a.icons or os.path.join(root, 'icons')
out = a.out or os.path.join(root, 'src', 'icon_data.h')


def rle(body):
    blocks = [body[i:i + 16] for i in range(0, len(body), 16)]
    res = bytearray(); i = 0
    while i < len(blocks):
        j = i
        while j < len(blocks) and blocks[j] == blocks[i] and j - i < 255: j += 1
        res.append(j - i); res += blocks[i]; i = j
    return bytes(res)


def carr(name, data):
    lines = ['static const unsigned char %s[] = {' % name]
    for k in range(0, len(data), 32):
        lines.append(','.join(str(b) for b in data[k:k + 32]) + ',')
    lines.append('0};')
    return '\n'.join(lines) + '\n'


items = []
for f in sorted(glob.glob(os.path.join(icons, '*.png'))):
    base = os.path.splitext(os.path.basename(f))[0]
    large = base.endswith('_LG')
    slot = base[:-3] if large else base
    img = Image.open(f)
    want = swatch.SIZES['large' if large else 'small']
    if img.size != want:
        print('warning: %s is %dx%d, it should be %dx%d (scaled)' % (os.path.basename(f), img.size[0], img.size[1], *want))
    data = swatch.png_to_swatchbin(img, 'large' if large else 'small')
    items.append((slot, large, rle(data[0x53:])))

o = ['/* Generated by scripts/gen_icons.py from the PNGs in icons/ - do not edit. */\n#pragma once\n']
o.append(carr('k_icon_hdr_small', swatch.HDR_SMALL)); o.append(carr('k_icon_hdr_large', swatch.HDR_LARGE))
tbl = []
for n, (slot, large, data) in enumerate(items):
    o.append(carr('k_icon_d%d' % n, data))
    tbl.append('    {"%s", %d, k_icon_d%d, %d},' % (slot, 1 if large else 0, n, len(data)))
o.append('typedef struct { const char *slot; int large; const unsigned char *rle; unsigned rle_size; } IconEntry;\n')
o.append('#define ICON_COUNT %d\n' % len(items))
o.append('static const IconEntry k_icons[ICON_COUNT + 1] = {\n' + '\n'.join(tbl) + '\n    {0, 0, 0, 0}};\n')
o.append('#define ICON_PREFIX "%s"\n' % a.prefix)
open(out, 'w').write(''.join(o))
print('%s: %d icon(s)' % (out, len(items)), ', '.join(('%s%s' % (s, '_LG' if l else '')) for s, l, _ in items))
